/**
 * Level data. Every level is a chain of 16-column segments (12 rows each).
 *
 * Tiles:   "#" solid   "-" one-way platform   "^" thorns   "." empty
 * Actors:  "P" start   "c" chest   "E" exit   "X" boss arena   "S" Serrure
 *          "B" Bourdon "s" spore   "j" meduse "p" penitent   "a" rouage
 *          "w" loup    "r" reptile "k" colosse "g" golem      "m" souris
 *          "l" lys     "d" medallion
 */
import type { SongName } from "./audio";

export type Theme = "forest" | "chains" | "castle";
export type BossKind = "machine" | "decrocheur" | "sombre";

export type LevelDef = {
  index: number;
  theme: Theme;
  song: SongName;
  timeLimit: number;
  boss: BossKind;
  map: string[];
  width: number;
  height: number;
};

const ROWS = 12;

function seg(...rows: string[]): string[] {
  if (rows.length !== ROWS) throw new Error(`segment must have ${ROWS} rows`);
  const width = rows[0].length;
  for (const row of rows) {
    if (row.length !== width) throw new Error(`ragged segment row: ${row}`);
  }
  return rows;
}

function join(segments: string[][]): string[] {
  const out: string[] = [];
  for (let y = 0; y < ROWS; y += 1) {
    out.push(segments.map((s) => s[y]).join(""));
  }
  return out;
}

