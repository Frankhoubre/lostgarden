function level(
  index: number,
  theme: Theme,
  song: SongName,
  timeLimit: number,
  boss: BossKind,
  segments: string[][],
): LevelDef {
  const map = join(segments);
  return {
    index,
    theme,
    song,
    timeLimit,
    boss,
    map,
    width: map[0].length,
    height: ROWS,
  };
}

