import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Turns subtitle files into the transcript modules the site reads.
 *
 *   subtitles/en.srt  (or en.vtt)  ->  lib/transcripts/en.ts
 *
 * Export each language from YouTube Studio (Subtitles, three dots, Download,
 * .srt or .vtt), drop the files in `subtitles/`, run
 * `node scripts/import-subtitles.mjs`, commit the generated modules.
 * The transcript page appears only once all four languages are present.
 */

const ROOT = process.cwd();
const LOCALES = ["en", "fr", "ja", "ko"];

function toSeconds(stamp) {
  const [hms, ms = "0"] = stamp.trim().replace(",", ".").split(".");
  const parts = hms.split(":").map(Number);
  const [h, m, s] = parts.length === 3 ? parts : [0, parts[0], parts[1]];
  return h * 3600 + m * 60 + s + Number(`0.${ms}`);
}

function parse(content) {
  const cues = [];
  const blocks = content.replace(/\r/g, "").replace(/^WEBVTT[^\n]*\n/, "").split(/\n{2,}/);
  for (const block of blocks) {
    const lines = block.split("\n").filter(Boolean);
    const timing = lines.find((line) => line.includes("-->"));
    if (!timing) continue;
    const [start, end] = timing.split("-->").map((part) => toSeconds(part.split(" ")[0] || part));
    const text = lines
      .slice(lines.indexOf(timing) + 1)
      .join(" ")
      .replace(/<[^>]+>/g, "")
      .replace(/\s+/g, " ")
      .trim();
    if (text) cues.push({ start, end, text });
  }
  // Merge consecutive identical cues, which VTT exports often duplicate.
  return cues.filter((cue, index) => index === 0 || cue.text !== cues[index - 1].text);
}

function tsLiteral(cues) {
  const rows = cues
    .map((cue) => `  { start: ${cue.start.toFixed(2)}, end: ${cue.end.toFixed(2)}, text: ${JSON.stringify(cue.text)} },`)
    .join("\n");
  return rows ? `[\n${rows}\n]` : "[]";
}

for (const locale of LOCALES) {
  const source = [`${locale}.srt`, `${locale}.vtt`].map((name) => join(ROOT, "subtitles", name)).find(existsSync);
  const cues = source ? parse(readFileSync(source, "utf8")) : [];
  const name = `transcript${locale[0].toUpperCase()}${locale.slice(1)}`;
  const source_ts = `import type { Transcript } from "@/lib/transcript";

/**
 * Generated by \`node scripts/import-subtitles.mjs\` from \`subtitles/${locale}.srt\`
 * or \`subtitles/${locale}.vtt\`. Do not edit by hand; re-run the import.
 */
export const ${name}: Transcript = ${tsLiteral(cues)};
`;
  writeFileSync(join(ROOT, "lib", "transcripts", `${locale}.ts`), source_ts);
  console.log(`${locale}: ${source ? `${cues.length} cues from ${source.replace(ROOT + "/", "")}` : "no subtitle file, empty transcript"}`);
}
